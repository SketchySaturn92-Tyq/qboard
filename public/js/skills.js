/**
 * 按用户这句话命中的技能。
 *
 * enabledIds 语义（三种情况严格区分）：
 *   不传 / 传 null：不按启用集过滤，任何技能只要命中关键词就返回；
 *   传数组（含空数组）：只在该数组内匹配，空数组表示一个都不启用，直接返回 []；
 *   传非数组的其它值：视同不传。
 *
 * 注意 DEFAULT_ENABLED 是界面上的默认勾选预设，不是匹配白名单。
 * 想让匹配跟随界面勾选，调用方要显式把当前勾选列表传进来，例如
 * matchSkills(text, state.enabledSkills ?? DEFAULT_ENABLED)。
 *
 * 匹配规则：text 与 keyword 同时小写后做子串包含判断，命中任一关键词即算命中。
 * 返回顺序始终跟随 SKILLS 顺序，保证拼进系统提示时顺序稳定、可缓存。
 */
export function matchSkills(text, enabledIds = null) {
  const list = Array.isArray(enabledIds) ? enabledIds : null;
  if (list && list.length === 0) return [];
  const hay = String(text == null ? '' : text).toLowerCase();
  if (!hay.trim()) return [];

  const allow = list ? new Set(list) : null;
  return SKILLS.filter((skill) => {
    if (allow && !allow.has(skill.id)) return false;
    return skill.keywords.some((kw) => hay.includes(String(kw).toLowerCase()));
  });
}
